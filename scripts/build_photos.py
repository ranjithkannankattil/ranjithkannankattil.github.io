H = lambda s: html.escape(str(s), quote=True)  # noqa: E731


# ---------------------------------------------------------------- model helpers
def visits_newest(place):
    return sorted(place["visits"], key=lambda v: v["month"], reverse=True)


def latest(place):
    return visits_newest(place)[0]["month"]


def count(place):
    return len(pd.photos_of(place))


def place_url(p):
    return f"/photography/{p['id']}/"


def visit_url(p, v):
    return f"/photography/{p['id']}/{v['month']}/"


def plural(n, word):
    return f"{n} {word}{'' if n == 1 else 's'}"


def cameras(photos):
    seen = []
    for ph in photos:
        if ph.get("camera") and ph["camera"] not in seen:
            seen.append(ph["camera"])
    return ", ".join(seen)


def find(place, stem):
    for v in place["visits"]:
        for ph in v["photos"]:
            if ph["stem"] == stem:
                return v, ph
    raise KeyError(stem)


