"""Build the Photography pages from scripts/photos.json.

    python3 scripts/build_photos.py        (run from the repository root)

Writes photography/index.html (location cards), photography/<place>/index.html (every visit),
photography/<place>/<yyyy-mm>/index.html (one visit), link-preview images
assets/og/photo-<place>[-<yyyy-mm>].jpg, js/photo-links.js (old photography.html links → new
pages) and the photography entries in sitemap.xml. Stops if photos.json has problems.
"""
