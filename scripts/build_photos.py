# ---------------------------------------------------------------- old links, previews, sitemap
def old_links(data):
    """Old photography.html hashes ('tenby-4', and bare '12' = Florence) → new addresses.
    A photo that was removed goes to its visit page."""
    out, olds = {}, {}
    for p in data["places"]:
        for v in p["visits"]:
            for i, ph in enumerate(v["photos"], 1):
                if ph.get("old"):
                    out[ph["old"]] = f"{visit_url(p, v)}#{i}"
                    olds.setdefault(ph["old"].rsplit("-", 1)[0], (p, v, set()))[2].add(int(ph["old"].rsplit("-", 1)[1]))
    for name, (p, v, have) in olds.items():
        for n in range(1, max(have) + 1):
            out.setdefault(f"{name}-{n}", visit_url(p, v))
    for k in list(out):
        if k.startswith("florence-"):
            out[k.split("-", 1)[1]] = out[k]
    return dict(sorted(out.items(), key=lambda kv: (not kv[0][0].isdigit(), kv[0])))


def og_image(src, dest):
    from PIL import Image
    im = Image.open(src).convert("RGB")
    W, Hh = im.size
    tw, th = 1200, 630
    s = max(tw / W, th / Hh)
    im = im.resize((round(W * s), round(Hh * s)), Image.LANCZOS)
    l, t = (im.width - tw) // 2, (im.height - th) // 2
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.crop((l, t, l + tw, t + th)).save(dest, "JPEG", quality=82, optimize=True)


def update_sitemap(path, urls):
    s = path.read_text()
    s = re.sub(r"\s*<url><loc>https://ranjithkb\.com/photography[^<]*</loc></url>", "", s)
    lines = "".join(f"\n  <url><loc>{SITE}{u}</loc></url>" for u in urls)
    s = s.replace(f"<url><loc>{SITE}/</loc></url>", f"<url><loc>{SITE}/</loc></url>{lines}", 1)
    path.write_text(s)


def build(data, root, images=True):
    root = Path(root)
    written = []
    # start clean: a place or month removed from photos.json must not stay online
    if (root / "photography").exists():
        shutil.rmtree(root / "photography")
    for f in (root / "assets/og").glob("photo-*.jpg"):
        f.unlink()

    def write(rel, text):
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
        written.append(f)

    write("photography/index.html", cards_page(data))
    urls = ["/photography/"]
    for p in data["places"]:
        write(f"photography/{p['id']}/index.html", place_page(p))
        urls.append(place_url(p))
        for v in visits_newest(p):
            write(f"photography/{p['id']}/{v['month']}/index.html", visit_page(p, v))
            urls.append(visit_url(p, v))
            if images:
                og_image(root / pd.WEB / v["photos"][0]["full"], root / f"assets/og/photo-{p['id']}-{v['month']}.jpg")
        if images:
            _, key = find(p, p["key"])
            og_image(root / pd.WEB / key["full"], root / f"assets/og/photo-{p['id']}.jpg")
    links_js = ("// AUTO-GENERATED by scripts/build_photos.py — old photography.html links → new pages.\n"
                "window.PHOTO_LINKS = " + json.dumps(old_links(data), indent=1, ensure_ascii=False) + ";\n")
    write("js/photo-links.js", links_js)
    # versioned, so returning visitors never use a cached list from before a rebuild
    write("photography.html", FORWARDER.replace("{V}", hashlib.sha1(links_js.encode()).hexdigest()[:8]))
    update_sitemap(root / "sitemap.xml", urls)
    return written


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    data = pd.load(here / "photos.json")
    errs = pd.validate(data, here.parent)
    if errs:
        sys.exit("photos.json has problems:\n  " + "\n  ".join(errs))
    files = build(data, here.parent)
    print(f"wrote {len(files)} files")
