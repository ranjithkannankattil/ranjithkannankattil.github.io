/**
 * The app's own words in English, Malayalam or Hindi (his ask, Nov 2026). English is written in the code as it always was;
 * [t] swaps it for the chosen language when there is a translation (anything missing stays English). Station and song
 * names are never translated. The choice is in Settings → App language and, on Android 13+, also in the phone's own
 * Settings → Apps → Radio Velvet → Language. Malayalam word choices: docs/radio-malayalam-words.md on the website repo.
 */
object Lang {
    val CODES = listOf("en", "ml", "hi")
    val NAMES = mapOf("en" to "English", "ml" to "മലയാളം", "hi" to "हिन्दी")
    var code by mutableStateOf("en")

    private fun p(ctx: Context) = ctx.getSharedPreferences("settings", Context.MODE_PRIVATE)
    /** The phone's per-app language (Android 13+) wins, then our own setting; English by default. */
    fun load(ctx: Context) {
        val sys = if (Build.VERSION.SDK_INT >= 33) runCatching {
            ctx.getSystemService(LocaleManager::class.java)?.applicationLocales?.takeIf { !it.isEmpty }?.get(0)?.language }.getOrNull() else null
        code = (sys ?: p(ctx).getString("lang", "en")!!).let { if (it in CODES) it else "en" }
    }
    fun set(ctx: Context, c: String) {
        code = if (c in CODES) c else "en"
        p(ctx).edit().putString("lang", code).apply()
        if (Build.VERSION.SDK_INT >= 33) runCatching {
            ctx.getSystemService(LocaleManager::class.java)?.applicationLocales =
                if (code == "en") LocaleList.getEmptyLocaleList() else LocaleList.forLanguageTags(code) }
    }
    fun tr(s: String): String = when (code) { "ml" -> ML[s]; "hi" -> HI[s]; else -> null } ?: s

