 * [t] swaps it for the chosen language when there is a translation (anything missing stays English). Station and song
 * names are never translated. The choice is in Settings → App language and, on Android 13+, also in the phone's own
 * Settings → Apps → Radio Velvet → Language. Malayalam word choices: docs/radio-malayalam-words.md on the website repo.
